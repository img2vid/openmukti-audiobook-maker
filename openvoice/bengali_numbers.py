def whole(n):
    if n<100:
        return _SMALL[n]
    for size,label in ((10_000_000,'কোটি'),(100_000,'লক্ষ'),(1_000,'হাজার'),(100,'শত')):
        if n>=size:
            major,minor=divmod(n,size)
            return whole(major)+' '+label+(' '+whole(minor) if minor else '')


def spoken(value):
    n=Decimal(str(value))
    if not n.is_finite() or len(n.as_tuple().digits)>120:
        raise ValueError('Number exceeds Bengali narration limit')
    left,_,right=format(abs(n),'f').partition('.')
    return ('ঋণাত্মক ' if n<0 else '')+whole(int(left))+(' দশমিক '+' '.join(_SMALL[int(c)] for c in right) if right and int(right) else '')
